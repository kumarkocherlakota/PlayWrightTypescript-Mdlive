import type { TracedScenario } from './collect-scenarios';
import type { CoverageSummary, MatrixRow, TraceabilityMatrix } from './build-matrix';
import type { ExecutionResult } from './execution-results';

export interface RenderOptions {
  /** Include execution results. The committed matrix never does (results belong to a run). */
  readonly withResults: boolean;
  readonly catalogueFile: string;
}

/** Renders the matrix as Markdown. Deterministic for the same input, so drift can be checked. */
export function renderMatrix(matrix: TraceabilityMatrix, options: RenderOptions): string {
  return [
    '# Traceability matrix',
    '',
    'Generated by `npm run traceability` from feature tags and',
    `\`${options.catalogueFile}\`. Do not edit by hand.`,
    '',
    '> The requirements are **synthetic reference requirements** for the local reference portal.',
    '> Passing scenarios demonstrate behaviour of that synthetic app only and establish no',
    '> regulatory compliance.',
    '',
    ...resultsNote(matrix, options),
    '',
    '## Coverage summary',
    '',
    ...renderCoverage(matrix.coverage, options.withResults),
    '',
    '## Requirement → scenario → result',
    '',
    '| Requirement | Acceptance criterion | Feature | Scenario | Layer | Intent | Mode | Test file | Execution result | Defect |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
    ...matrix.rows.map((row) => renderRow(row, options.withResults)),
    '',
    ...renderIssues(matrix.issues),
  ].join('\n');
}

function resultsNote(matrix: TraceabilityMatrix, options: RenderOptions): string[] {
  if (!options.withResults) {
    return [
      'Execution results are deliberately not part of this committed file: a scenario listed here',
      'is defined, not executed. Results of a run are in `reports/traceability/` after',
      '`npm test` (or `npm run traceability` with a recorded run).',
    ];
  }
  return [
    `Execution results come from the run recorded at ${matrix.runStartedAt ?? 'an unknown time'}.`,
    '"Not run" means the scenario was not part of that run; it is not a pass.',
  ];
}

function renderCoverage(coverage: CoverageSummary, withResults: boolean): string[] {
  const { requirements, criteria, scenarios } = coverage;
  const lines = [
    '| Measure | Count |',
    '| --- | --- |',
    `| Requirements | ${requirements.total} |`,
    `| Requirements fully covered by automated scenarios | ${requirements.automated} |`,
    `| Requirements with manual-only criteria | ${requirements['manual only']} |`,
    `| Requirements with blocked criteria | ${requirements['blocked only']} |`,
    `| Requirements with uncovered criteria | ${requirements['not covered']} |`,
    `| Acceptance criteria | ${criteria.total} |`,
    `| Acceptance criteria covered by automated scenarios | ${criteria.automated} |`,
    `| Acceptance criteria covered by manual scenarios only | ${criteria['manual only']} |`,
    `| Acceptance criteria covered by blocked scenarios only | ${criteria['blocked only']} |`,
    `| Acceptance criteria not covered | ${criteria['not covered']} |`,
    `| Traced scenarios | ${scenarios.total} |`,
    `| UI scenarios | ${scenarios.byLayer.UI} |`,
    `| API scenarios | ${scenarios.byLayer.API} |`,
    `| UI + API integration scenarios | ${scenarios.byLayer['UI + API']} |`,
    ...Object.entries(scenarios.byIntent).map(
      ([intent, count]) => `| ${capitalize(intent)} scenarios | ${count} |`,
    ),
    `| Automated scenarios | ${scenarios.byMode.automated} |`,
    `| Manual-only scenarios | ${scenarios.byMode.manual} |`,
    `| Blocked scenarios | ${scenarios.byMode.blocked} |`,
  ];
  const execution = coverage.execution;
  if (withResults && execution !== undefined) {
    lines.push(
      `| Automated scenarios passed in this run | ${execution.passed} |`,
      `| Automated scenarios failed in this run | ${execution.failed} |`,
      `| Automated scenarios skipped in this run | ${execution.skipped} |`,
      `| Automated scenarios that passed only on retry (flaky) | ${execution.flaky} |`,
      `| Automated scenarios not run | ${execution.notRun} |`,
    );
  }
  return lines;
}

function renderRow(row: MatrixRow, withResults: boolean): string {
  const scenario = row.scenario;
  if (scenario === undefined) {
    return `| ${row.requirementId} | ${row.criterionId} | — | **Not covered** | — | — | — | — | — | — |`;
  }
  return [
    '',
    row.requirementId,
    row.criterionId,
    escape(scenario.feature),
    escape(scenario.name),
    scenario.layer,
    scenario.intents.join(', ') || '—',
    scenario.mode,
    `\`${scenario.location}\``,
    resultText(scenario, row.result, withResults),
    scenario.defects.join(', ') || '—',
    '',
  ]
    .join(' | ')
    .trim();
}

function resultText(
  scenario: TracedScenario,
  result: ExecutionResult | undefined,
  withResults: boolean,
): string {
  if (scenario.mode === 'manual') {
    return 'Manual (not automated)';
  }
  if (scenario.mode === 'blocked') {
    return 'Blocked (not executed)';
  }
  if (!withResults) {
    return 'See run report';
  }
  if (result === undefined || result.status === 'unknown') {
    return 'Not run';
  }
  const retries = result.attempts > 1 ? ` after ${result.attempts} attempts` : '';
  return `${capitalize(result.status)}${result.flaky ? ' (flaky)' : ''}${retries}`;
}

function renderIssues(issues: readonly string[]): string[] {
  if (issues.length === 0) {
    return ['No traceability issues.', ''];
  }
  return ['## Traceability issues', '', ...issues.map((issue) => `- ${escape(issue)}`), ''];
}

function escape(text: string): string {
  return text.replace(/\|/g, '\\|');
}

function capitalize(text: string): string {
  return text.charAt(0).toUpperCase() + text.slice(1);
}
